const strich = (c, breite = 4) => ({ fill: 'none', stroke: c, 'stroke-width': breite, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' });
const stern = (spitzen, aussen, innen, drehung = -90) => {
  const p = [];
  for (let i = 0; i < spitzen * 2; i++) {
    const r = i % 2 ? innen : aussen, w = ((drehung + (i * 180) / spitzen) * Math.PI) / 180;
    p.push(`${(r * Math.cos(w)).toFixed(1)} ${(r * Math.sin(w)).toFixed(1)}`);
  }
  return `M${p.join(' L')} Z`;
};

